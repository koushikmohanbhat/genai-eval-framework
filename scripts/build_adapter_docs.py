"""Regenerate docs/adapters.md from the adapter catalog and a conformance run (CI checks it is up to date).

    python scripts/build_adapter_docs.py
"""
from __future__ import annotations

from pathlib import Path

from genai_evals import conformance, plugins

ROOT = Path(__file__).resolve().parents[1]


def render() -> str:
    res = conformance.run(conformance.builtin_specs())
    return f"""# Adapters and their status

Generated by `python scripts/build_adapter_docs.py` from the adapter catalog and a conformance run; do not edit by
hand. How the levels are defined, and how to add an adapter: [plugins](plugins.md).

**No built-in adapter is live tested or customer validated yet.** Those levels are recorded per project in
`validation.yaml` (`genai-evals adapters record`), and every report shows the effective status of the adapters a run
used. Run `genai-evals adapters` in a project to see the catalog with that project's records applied.

## Catalog

{plugins.markdown_table()}
## Conformance results

{conformance.matrix_markdown(res)}"""


def main() -> int:
    (ROOT / "docs" / "adapters.md").write_text(render(), encoding="utf-8")
    print("wrote docs/adapters.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

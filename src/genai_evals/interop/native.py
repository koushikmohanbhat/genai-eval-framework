"""Managed eval services: AgentCore Evaluations (AWS) and the Vertex Gen AI evaluation service (Google Cloud).

The framework's own graders stay the default so scores are comparable across clouds; these helpers bring managed
results into the same report, and package framework graders as AgentCore code-based evaluators (Lambda).
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from ..models import Score

LAMBDA_HANDLER = '''"""AgentCore Evaluations code-based evaluator generated by `genai-evals agentcore package-evaluator`.

Runs a genai-evals grader on the OTel spans AgentCore passes in. EXPERIMENTAL: check the event shape your AgentCore
Evaluations version sends (spans may arrive under "spans", "sessionSpans" or "evaluationInput") and adjust EVENT_KEYS.
"""
import asyncio
import json
import os

from genai_evals.config import GraderSpec, SuiteSpec
from genai_evals.graders import GradeContext, build_grader
from genai_evals.models import Case
from genai_evals.sources.normalize import spans_to_samples

GRADER = json.loads(os.environ.get("GENAI_EVALS_GRADER", {grader_json!r}))
EVENT_KEYS = ("spans", "sessionSpans", "evaluationInput")


def _spans(event):
    for k in EVENT_KEYS:
        v = event.get(k)
        if isinstance(v, dict):
            v = v.get("sessionSpans") or v.get("spans")
        if v:
            return v
    return []


def handler(event, context):
    spans = _spans(event)
    samples = spans_to_samples(spans, origin="agentcore")
    if not samples:
        return {{"label": "SKIPPED", "explanation": "no spans in event"}}
    s = samples[0]
    grader = build_grader(GraderSpec(**GRADER), GradeContext(suite=SuiteSpec(name="agentcore-evaluator", tokenize=False)))
    sc = asyncio.run(grader.grade(s, Case(id=s.case_id, input=s.input or "")))
    return {{"value": sc.value, "label": "PASS" if sc.passed else "FAIL", "explanation": sc.reasoning or json.dumps(sc.details)[:1000]}}
'''


def package_agentcore_evaluator(grader: dict[str, Any], out_dir: str | Path) -> Path:
    if grader.get("type") in {"rubric", "pairwise", "reference_match", "policy", "faithfulness", "answer_relevance"}:
        raise ValueError("package deterministic graders as code-based evaluators; use AgentCore's own LLM-as-judge evaluators for model graders")
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "handler.py").write_text(LAMBDA_HANDLER.format(grader_json=json.dumps(grader)), encoding="utf-8")
    (out / "requirements.txt").write_text("genai-eval-framework\n", encoding="utf-8")
    (out / "README.md").write_text(
        f"# AgentCore code-based evaluator: {grader['name']}\n\nBuild: `pip install -r requirements.txt -t package && cp handler.py package/`, "
        "zip `package/`, create a Lambda (Python 3.12) with handler `handler.handler`, then register it as a custom code-based "
        "evaluator in AgentCore Evaluations and grant AgentCore permission to invoke it.\n", encoding="utf-8")
    return out


def import_agentcore_results(records: list[dict[str, Any]], key_by: str = "session") -> list[Score]:
    """Map AgentCore Evaluations result records (from the results log group) to Scores keyed by session or trace id.
    Field names are read tolerantly; the evaluator name becomes `agentcore:<evaluator>`."""
    out = []
    for r in records:
        r = r.get("message", r) if isinstance(r.get("message"), dict) else r
        ev = r.get("evaluatorName") or r.get("evaluatorId") or r.get("evaluator") or "evaluator"
        sid = r.get("sessionId") or r.get("session_id") or (r.get("context") or {}).get("sessionId")
        tid = r.get("traceId") or r.get("trace_id")
        raw = r.get("value", r.get("score"))
        label = r.get("label")
        mx = float(r.get("maxValue") or r.get("max_score") or 1.0)
        value = float(raw) / mx if isinstance(raw, (int, float)) else (1.0 if str(label).upper() in {"PASS", "YES", "TRUE"} else 0.0 if label else None)
        out.append(Score(grader=f"agentcore:{str(ev).split('/')[-1]}", case_id=str((sid if key_by == "session" else tid) or tid or sid),
                         target=r.get("target", "agentcore"), value=value, passed=None if value is None else value >= float(r.get("threshold", 0.5)),
                         label=label, reasoning=r.get("explanation") or r.get("reason"), details={"source": "agentcore_evaluations"}))
    return out


def import_vertex_eval(rows: list[dict[str, Any]], metrics: list[str] | None = None, max_score: float = 5.0, id_field: str = "id",
                       target: str = "vertex") -> list[Score]:
    """Map a Gen AI evaluation service metrics table (rows with '<metric>/score' and '<metric>/explanation') to Scores."""
    out = []
    for i, r in enumerate(rows):
        names = metrics or sorted({k.split("/")[0] for k in r if k.endswith("/score")})
        for m in names:
            v = r.get(f"{m}/score")
            if v is None:
                continue
            val = float(v) / max_score if float(v) > 1 else float(v)
            out.append(Score(grader=f"vertex:{m}", case_id=str(r.get(id_field, i)), target=r.get("target", target), value=val, passed=val >= 0.5,
                             reasoning=r.get(f"{m}/explanation"), details={"source": "vertex_gen_ai_eval"}))
    return out



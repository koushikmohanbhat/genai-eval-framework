"""Prompts as code.

Layout (one folder per immutable version):

    prompts/
      claims_agent/
        1.3.2/  prompt.yaml  system.md.j2  tools.yaml  examples.jsonl
        1.4.0/  ...
    prompts.lock

`prompts.lock` records each version's content hash and which version each stage (dev / staging / prod)
points at. A locked version's content can never change: edit -> new version folder -> lock -> gate -> promote.

Runtime use (dependency-light, safe to import in production):

    from genai_evals.prompts import load
    p = load("claims_agent", stage="prod", variables={"language": "en"})
    p.system, p.tools, p.examples, p.model_hints, p.version, p.hash
"""
from __future__ import annotations

import difflib
import hashlib
import json
import os
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml
from jinja2 import StrictUndefined
from jinja2.sandbox import SandboxedEnvironment

SEMVER = re.compile(r"^(\d+)\.(\d+)\.(\d+)(?:-[0-9A-Za-z.-]+)?$")
STAGES = ("dev", "staging", "prod")
_env = SandboxedEnvironment(undefined=StrictUndefined, autoescape=False, keep_trailing_newline=True)


def _semver_key(v: str) -> tuple:
    m = SEMVER.match(v)
    return tuple(int(x) for x in m.groups()) if m else (0, 0, 0)


@dataclass
class PromptVersion:
    id: str
    version: str
    path: Path
    meta: dict[str, Any]
    hash: str

    @property
    def data_elements(self) -> set[str]:
        return set(self.meta.get("data_elements", []))

    @property
    def purposes(self) -> set[str]:
        return set(self.meta.get("purposes", []))

    def files(self) -> dict[str, str]:
        return {str(p.relative_to(self.path)): p.read_text(encoding="utf-8") for p in sorted(self.path.rglob("*")) if p.is_file()}


@dataclass
class RenderedPrompt:
    id: str
    version: str
    hash: str
    system: str | None
    template: str | None
    tools: list[dict[str, Any]] = field(default_factory=list)
    examples: list[dict[str, Any]] = field(default_factory=list)
    model_hints: dict[str, Any] = field(default_factory=dict)
    output_schema: dict[str, Any] | None = None
    meta: dict[str, Any] = field(default_factory=dict)

    def render_user(self, variables: dict[str, Any]) -> str:
        if not self.template:
            return str(variables.get("input", ""))
        return _env.from_string(self.template).render(**variables)

    @property
    def ref(self) -> str:
        return f"{self.id}@{self.version}"


def content_hash(folder: Path) -> str:
    h = hashlib.sha256()
    for p in sorted(folder.rglob("*")):
        if p.is_file():
            h.update(str(p.relative_to(folder)).replace(os.sep, "/").encode())
            h.update(b"\0")
            h.update(p.read_bytes().replace(b"\r\n", b"\n"))
            h.update(b"\0")
    return "sha256:" + h.hexdigest()


class PromptStore:
    def __init__(self, root: str | Path = "prompts", lock_path: str | Path | None = None):
        self.root = Path(root)
        self.lock_path = Path(lock_path) if lock_path else self.root.parent / "prompts.lock"

    # ---- discovery -----------------------------------------------------
    def ids(self) -> list[str]:
        return sorted(p.name for p in self.root.iterdir() if p.is_dir()) if self.root.exists() else []

    def versions(self, prompt_id: str) -> list[str]:
        d = self.root / prompt_id
        if not d.exists():
            raise KeyError(f"prompt '{prompt_id}' not found under {self.root}")
        return sorted((p.name for p in d.iterdir() if p.is_dir() and SEMVER.match(p.name)), key=_semver_key)

    def get(self, prompt_id: str, version: str) -> PromptVersion:
        path = self.root / prompt_id / version
        meta_path = path / "prompt.yaml"
        if not meta_path.exists():
            raise KeyError(f"prompt '{prompt_id}@{version}' not found (expected {meta_path})")
        meta = yaml.safe_load(meta_path.read_text(encoding="utf-8")) or {}
        if str(meta.get("version", version)) != version:
            raise ValueError(f"{meta_path}: version field '{meta.get('version')}' does not match folder '{version}'")
        if meta.get("id", prompt_id) != prompt_id:
            raise ValueError(f"{meta_path}: id field '{meta.get('id')}' does not match folder '{prompt_id}'")
        return PromptVersion(prompt_id, version, path, meta, content_hash(path))

    # ---- lock file -----------------------------------------------------
    def read_lock(self) -> dict[str, Any]:
        if not self.lock_path.exists():
            return {"prompts": {}}
        return yaml.safe_load(self.lock_path.read_text(encoding="utf-8")) or {"prompts": {}}

    def write_lock(self, lock: dict[str, Any]) -> None:
        self.lock_path.write_text("# generated by `genai-evals prompts lock`; edit stages with `genai-evals prompts promote`\n"
                                  + yaml.safe_dump(lock, sort_keys=True), encoding="utf-8")

    def resolve(self, ref: str, stage: str = "prod") -> PromptVersion:
        """'id@1.2.0' -> that version; 'id' -> version the stage points at (or the latest if unlocked)."""
        pid, _, ver = ref.partition("@")
        if not ver:
            entry = self.read_lock().get("prompts", {}).get(pid, {})
            ver = entry.get("stages", {}).get(stage) or (self.versions(pid) or [None])[-1]
            if not ver:
                raise KeyError(f"prompt '{pid}' has no versions")
        return self.get(pid, ver)

    def lock(self) -> dict[str, list[str]]:
        """Record hashes for new versions. Returns {'added': [...], 'unchanged': [...]}. Refuses edits to locked versions."""
        problems = [p for p in self.check() if "changed after it was locked" in p]
        if problems:
            raise ValueError("; ".join(problems))
        lock = self.read_lock()
        added, unchanged = [], []
        for pid in self.ids():
            entry = lock["prompts"].setdefault(pid, {"versions": {}, "stages": {}})
            for v in self.versions(pid):
                pv = self.get(pid, v)
                if v in entry["versions"]:
                    unchanged.append(f"{pid}@{v}")
                else:
                    entry["versions"][v] = pv.hash
                    added.append(f"{pid}@{v}")
            if not entry["stages"].get("dev") and entry["versions"]:
                entry["stages"]["dev"] = sorted(entry["versions"], key=_semver_key)[-1]
        self.write_lock(lock)
        return {"added": added, "unchanged": unchanged}

    def check(self) -> list[str]:
        """CI check: every version folder is locked and no locked version has been edited."""
        problems = []
        lock = self.read_lock().get("prompts", {})
        for pid in self.ids():
            entry = lock.get(pid, {"versions": {}, "stages": {}})
            for v in self.versions(pid):
                try:
                    pv = self.get(pid, v)
                except (KeyError, ValueError) as e:
                    problems.append(str(e))
                    continue
                locked = entry.get("versions", {}).get(v)
                if locked is None:
                    problems.append(f"{pid}@{v} is not in prompts.lock (run `genai-evals prompts lock`)")
                elif locked != pv.hash:
                    problems.append(f"{pid}@{v} changed after it was locked: create a new version folder instead of editing a released one")
            for stage, v in entry.get("stages", {}).items():
                if v not in entry.get("versions", {}):
                    problems.append(f"{pid}: stage '{stage}' points at unknown version {v}")
        for pid in lock:
            if pid not in self.ids():
                problems.append(f"prompts.lock lists '{pid}' but prompts/{pid}/ does not exist")
        return problems

    def promote(self, prompt_id: str, version: str, stage: str) -> str | None:
        if stage not in STAGES:
            raise ValueError(f"stage must be one of {STAGES}")
        lock = self.read_lock()
        entry = lock["prompts"].get(prompt_id)
        if not entry or version not in entry.get("versions", {}):
            raise KeyError(f"{prompt_id}@{version} is not locked; run `genai-evals prompts lock` first")
        if entry["versions"][version] != self.get(prompt_id, version).hash:
            raise ValueError(f"{prompt_id}@{version} content does not match its locked hash")
        previous = entry.setdefault("stages", {}).get(stage)
        entry["stages"][stage] = version
        self.write_lock(lock)
        return previous

    # ---- comparisons -----------------------------------------------------
    def diff(self, a: str, b: str) -> str:
        pa, pb = self.resolve(a), self.resolve(b)
        fa, fb = pa.files(), pb.files()
        out = []
        for name in sorted(set(fa) | set(fb)):
            out += difflib.unified_diff(fa.get(name, "").splitlines(True), fb.get(name, "").splitlines(True),
                                        fromfile=f"{pa.id}@{pa.version}/{name}", tofile=f"{pb.id}@{pb.version}/{name}")
        return "".join(out)

    def dpdp_changes(self, candidate: str, against_stage: str = "prod") -> dict[str, set[str]]:
        """New data elements / purposes a candidate version touches compared with the version in a stage."""
        cand = self.resolve(candidate)
        try:
            base = self.resolve(cand.id, stage=against_stage)
        except KeyError:
            return {"data_elements": cand.data_elements, "purposes": cand.purposes}
        return {"data_elements": cand.data_elements - base.data_elements, "purposes": cand.purposes - base.purposes}

    # ---- rendering -------------------------------------------------------
    def render(self, ref: str, stage: str = "prod", variables: dict[str, Any] | None = None) -> RenderedPrompt:
        pv = self.resolve(ref, stage)
        meta = pv.meta
        variables = dict(variables or {})

        def _read(name: str | None) -> str | None:
            if not name:
                return None
            p = pv.path / name
            return p.read_text(encoding="utf-8") if p.exists() else None

        system_src = _read(meta.get("system", "system.md.j2" if (pv.path / "system.md.j2").exists() else None))
        ctx = {k: "" for k in meta.get("variables", [])}
        ctx.update(variables)
        system = _env.from_string(system_src).render(**ctx) if system_src else None
        template = _read(meta.get("template", "user.md.j2" if (pv.path / "user.md.j2").exists() else None))
        tools_src = _read(meta.get("tools", "tools.yaml" if (pv.path / "tools.yaml").exists() else None))
        tools = (yaml.safe_load(tools_src) or {}).get("tools", []) if tools_src else []
        ex_src = _read(meta.get("examples", "examples.jsonl" if (pv.path / "examples.jsonl").exists() else None))
        examples = [json.loads(line) for line in ex_src.splitlines() if line.strip()] if ex_src else []
        schema = None
        if meta.get("output_schema"):
            sp = (pv.path / meta["output_schema"])
            schema = json.loads(sp.read_text(encoding="utf-8")) if sp.exists() else None
        rp = RenderedPrompt(pv.id, pv.version, pv.hash, system, template, tools, examples,
                            dict(meta.get("model_hints", {})), schema, meta)
        _annotate_span(rp)
        return rp


def _annotate_span(rp: RenderedPrompt) -> None:
    """Stamp prompt.id / prompt.version / prompt.hash on the current OTel span, if OTel is in use."""
    try:
        from opentelemetry import trace
    except ImportError:
        return
    span = trace.get_current_span()
    if span is not None and span.is_recording():
        span.set_attribute("prompt.id", rp.id)
        span.set_attribute("prompt.version", rp.version)
        span.set_attribute("prompt.hash", rp.hash)


_default_store: PromptStore | None = None


def load(prompt_id: str, stage: str | None = None, version: str | None = None, variables: dict[str, Any] | None = None,
         root: str | Path | None = None) -> RenderedPrompt:
    """Runtime entry point. Root defaults to $GENAI_EVALS_PROMPTS_DIR or ./prompts; stage to $GENAI_EVALS_PROMPT_STAGE or prod."""
    global _default_store
    if root is not None:
        store = PromptStore(root)
    else:
        if _default_store is None:
            _default_store = PromptStore(os.environ.get("GENAI_EVALS_PROMPTS_DIR", "prompts"))
        store = _default_store
    ref = f"{prompt_id}@{version}" if version else prompt_id
    return store.render(ref, stage or os.environ.get("GENAI_EVALS_PROMPT_STAGE", "prod"), variables)


# ---- registry sync (mirror; the repo stays the source of truth) -----------
def bedrock_payload(rp: RenderedPrompt, model_id: str | None = None) -> dict[str, Any]:
    """Payload for bedrock-agent CreatePrompt. Bedrock variables use {{name}}, which matches simple Jinja variables."""
    variables = [{"name": v} for v in rp.meta.get("variables", [])]
    text = (rp.system or "") + ("\n\n" + rp.template if rp.template else "")
    variant: dict[str, Any] = {"name": "default", "templateType": "TEXT",
                               "templateConfiguration": {"text": {"text": text, "inputVariables": variables}}}
    if model_id or rp.model_hints.get("bedrock_model_id"):
        variant["modelId"] = model_id or rp.model_hints["bedrock_model_id"]
    return {"name": rp.id.replace("_", "-"), "description": f"{rp.ref} {rp.hash}"[:200], "defaultVariant": "default", "variants": [variant]}


def langfuse_payload(rp: RenderedPrompt, label: str | None = None) -> dict[str, Any]:
    messages = []
    if rp.system:
        messages.append({"role": "system", "content": rp.system})
    if rp.template:
        messages.append({"role": "user", "content": rp.template})
    return {"name": rp.id, "type": "chat", "prompt": messages, "labels": [label] if label else [],
            "config": {"version": rp.version, "hash": rp.hash, "model_hints": rp.model_hints, "tools": rp.tools},
            "commitMessage": rp.meta.get("changelog", "")}


def push(rp: RenderedPrompt, to: str, dry_run: bool = True, **kw) -> dict[str, Any]:
    if to == "bedrock":
        payload = bedrock_payload(rp, kw.get("model_id"))
        if dry_run:
            return {"target": "bedrock", "payload": payload}
        import boto3
        c = boto3.client("bedrock-agent", region_name=kw.get("region"))
        existing = {p["name"]: p["id"] for p in c.list_prompts().get("promptSummaries", [])}
        if payload["name"] in existing:
            pid = existing[payload["name"]]
            c.update_prompt(promptIdentifier=pid, **payload)
        else:
            pid = c.create_prompt(**payload)["id"]
        ver = c.create_prompt_version(promptIdentifier=pid, description=f"{rp.ref} {rp.hash}"[:200])
        return {"target": "bedrock", "prompt_id": pid, "version": ver.get("version")}
    if to == "langfuse":
        payload = langfuse_payload(rp, kw.get("label"))
        if dry_run:
            return {"target": "langfuse", "payload": payload}
        import base64
        import urllib.request
        host = kw.get("host") or os.environ.get("LANGFUSE_HOST", "https://cloud.langfuse.com")
        auth = base64.b64encode(f"{os.environ['LANGFUSE_PUBLIC_KEY']}:{os.environ['LANGFUSE_SECRET_KEY']}".encode()).decode()
        req = urllib.request.Request(f"{host}/api/public/v2/prompts", data=json.dumps(payload).encode(),
                                     headers={"Authorization": f"Basic {auth}", "Content-Type": "application/json"}, method="POST")
        with urllib.request.urlopen(req, timeout=30) as r:  # noqa: S310 (host is operator-configured)
            return {"target": "langfuse", "response": json.loads(r.read() or b"{}")}
    if to == "vertex":
        payload = {"prompt_name": rp.id, "system_instruction": rp.system, "prompt_data": rp.template,
                   "model_name": rp.model_hints.get("vertex_model"), "version_name": rp.version}
        if dry_run:
            return {"target": "vertex", "payload": payload}
        # Experimental: Vertex AI prompt management SDK surface is in preview and may change.
        import vertexai  # type: ignore
        from vertexai.preview import prompts as vprompts  # type: ignore
        vertexai.init(project=kw.get("project"), location=kw.get("location"))
        p = vprompts.Prompt(prompt_name=rp.id, prompt_data=rp.template or "", system_instruction=rp.system,
                            model_name=rp.model_hints.get("vertex_model"))
        saved = vprompts.create_version(prompt=p, version_name=rp.version)
        return {"target": "vertex", "prompt_id": getattr(saved, "prompt_id", None), "version": getattr(saved, "version_id", None)}
    raise ValueError("push target must be bedrock, vertex or langfuse")
